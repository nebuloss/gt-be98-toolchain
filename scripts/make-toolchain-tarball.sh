#!/usr/bin/env bash
# Produce a CLEAN, minimal GT-BE98 cross-toolchain tarball containing only the
# crosstools variants the GT-BE98 firmware build actually invokes.
#
# The upstream RMerl/am-toolchains checkout ships 9 cross-compiler variants
# (~2.7G under brcm-arm-hnd) plus an unused brcm-arm-sdk tree (~423M) and full
# git history. The GT-BE98 build only ever calls FOUR of them. This script
# extracts just those into a self-contained tarball suitable for seeding a
# Buildroot external-toolchain (BR2_TOOLCHAIN_EXTERNAL_CUSTOM) source.
#
# Usage:
#   scripts/make-toolchain-tarball.sh [SRC_BRCM_ARM_HND] [OUT_DIR]
#
#   SRC_BRCM_ARM_HND  path to .../toolchain/am-toolchains/brcm-arm-hnd
#                     (default: ../gt-be98-firmware/toolchain/am-toolchains/brcm-arm-hnd)
#   OUT_DIR           where to write the tarball + manifest (default: ./toolchain)
#
# The "required" list is derived empirically from a full build log:
#   grep -oE 'crosstools-[a-z0-9_.-]+' logs/run-*.out | sort | uniq -c
# Update REQUIRED below if a future SDK bump changes the invoked compilers.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
SRC="${1:-${HERE}/../gt-be98-firmware/toolchain/am-toolchains/brcm-arm-hnd}"
OUT_DIR="${2:-${HERE}/toolchain}"

# Cross-toolchain variants the GT-BE98 build invokes (see header).
REQUIRED=(
    crosstools-arm_softfp-gcc-10.3-linux-4.19-glibc-2.32-binutils-2.36.1  # primary userspace/kernel (ARM softfp)
    crosstools-arm-gcc-5.5-linux-4.1-glibc-2.26-binutils-2.28.1           # bootloader / legacy components
    crosstools-aarch64-gcc-10.3-linux-4.19-glibc-2.32-binutils-2.36.1     # 64-bit components
    crosstools-arm-gcc-10.3-linux-4.19-glibc-2.32-binutils-2.36.1         # misc ARM (gcc 10.3 hardfp)
)

TARBALL="${OUT_DIR}/gt-be98-toolchain-brcm-arm-hnd-minimal.tar.gz"
MANIFEST="${OUT_DIR}/MANIFEST.txt"

[[ -d "$SRC" ]] || { echo "ERROR: source toolchain not found: $SRC" >&2; exit 1; }
mkdir -p "$OUT_DIR"

echo "Source : $SRC"
echo "Output : $TARBALL"
echo "Staging required crosstools ..."

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
DEST="${STAGE}/brcm-arm-hnd"
mkdir -p "$DEST"

# Carry the upstream licence/readme if present (provenance).
for meta in ../LICENSE ../README.md; do
    [[ -f "${SRC}/${meta}" ]] && cp -a "${SRC}/${meta}" "${STAGE}/$(basename "$meta")" 2>/dev/null || true
done

for tc in "${REQUIRED[@]}"; do
    if [[ ! -d "${SRC}/${tc}" ]]; then
        echo "ERROR: required toolchain missing in source: ${tc}" >&2
        exit 1
    fi
    echo "  + ${tc}"
    cp -a "${SRC}/${tc}" "${DEST}/${tc}"
done

echo "Creating tarball (gzip) ..."
# pigz for parallel gzip if available, else gzip.
if command -v pigz >/dev/null 2>&1; then GZ="pigz"; else GZ="gzip"; fi
tar -C "$STAGE" -cf - . | "$GZ" > "$TARBALL"

echo "Writing manifest ..."
{
    echo "# GT-BE98 minimal cross-toolchain — generated by scripts/make-toolchain-tarball.sh"
    echo "# tarball: $(basename "$TARBALL")"
    echo "# layout : brcm-arm-hnd/<crosstools-...>  (drop-in for toolchain/am-toolchains/)"
    echo
    echo "## included crosstools variants"
    for tc in "${REQUIRED[@]}"; do
        printf '  %-72s %s\n' "$tc" "$(du -sh "${SRC}/${tc}" 2>/dev/null | cut -f1)"
    done
    echo
    echo "## tarball"
    printf '  size   : %s\n' "$(du -sh "$TARBALL" | cut -f1)"
    printf '  sha256 : %s\n' "$(sha256sum "$TARBALL" | cut -d' ' -f1)"
} > "$MANIFEST"

echo
echo "Done:"
echo "  $TARBALL ($(du -sh "$TARBALL" | cut -f1))"
echo "  $MANIFEST"
